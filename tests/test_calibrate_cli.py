# -- refusals ------------------------------------------------------------------


def test_missing_intrinsics_names_the_three_ways_to_supply_them(tmp_path, truth):
    """Focal length is not recoverable from these labels, so it must not be guessed."""
    project, _ = _labelled_project(tmp_path, truth)
    with pytest.raises(SystemExit, match="no intrinsics source"):
        cli.main(["calibrate", str(project.root), "--log-level", "error"])


def test_optics_derives_the_focal_from_a_datasheet(tmp_path, truth):
    """f_px = f_mm * W_px / W_mm -- two numbers off a lens/sensor datasheet.

    The values land on this rig's real focal (a long macro lens on a 1" sensor, which is
    what a microscope-like fly rig actually uses), so the solve succeeds too and the
    arithmetic is checked against something that works rather than in isolation.
    """
    project, _ = _labelled_project(tmp_path, truth)
    cli.main(
        [
            "calibrate",
            str(project.root),
            "--points",
            "landmarks",
            "--lens-mm",
            "233.209",
            "--sensor-mm",
            "10.0",
            "--name",
            "optics",
            "--log-level",
            "error",
        ]
    )
    cal = Calibration.load(project.root / "calibrations" / "optics.toml")
    assert cal.provenance["intrinsics"] == "optics"
    assert cal.cameras[CAMERA_NAMES[0]].intr[0] == pytest.approx(233.209 * 960 / 10.0)
    assert _centre_error_pct(truth, cal.cameras) < 2.0


def test_badly_wrong_intrinsics_fail_loudly_rather_than_quietly(tmp_path, truth):
    """A 4x-wrong focal must not yield a plausible-looking rig.

    This is the practical justification for refusing to guess intrinsics at all: with the
    focal wrong, the normalized coordinates the essential matrix and PnP work in are wrong
    and views cannot be placed. Failing here is the GOOD outcome -- the bad one would be a
    converged solve whose 3D is silently mis-scaled and mis-shaped.
    """
    project, _ = _labelled_project(tmp_path, truth)
    with pytest.raises(SystemExit, match="could not place view"):
        cli.main(
            [
                "calibrate",
                str(project.root),
                "--points",
                "landmarks",
                "--lens-mm",
                "50",
                "--sensor-mm",
                "8.8",
                "--name",
                "wrong",
                "--log-level",
                "error",
            ]
        )
    assert not (project.root / "calibrations" / "wrong.toml").exists()


def test_an_underdetermined_problem_is_refused_before_solving(tmp_path, truth, capsys):
    """It would converge to something plausible and then misproject everything."""
    project, _ = _labelled_project(
        tmp_path, truth, n_static=0, n_frames=1, n_kp=2, step=1
    )
    with pytest.raises(SystemExit, match="under-determined"):
        cli.main(
            [
                "calibrate",
                str(project.root),
                "--focal-px",
                FOCAL,
                "--log-level",
                "error",
            ]
        )
    assert "refusing" in capsys.readouterr().out
    assert not list((project.root / "calibrations").glob("*.toml"))


def test_unreviewed_frames_are_excluded_by_default(tmp_path, truth):
    """A half-labeled frame biases a track, and no residual reveals it afterwards."""
    project, _ = _labelled_project(tmp_path, truth, reviewed=False)
    with pytest.raises(SystemExit, match="nothing to calibrate from"):
        cli.main(
            [
                "calibrate",
                str(project.root),
                "--focal-px",
                FOCAL,
                "--log-level",
                "error",
            ]
        )
    # ...and can be opted into.
    cli.main(
        [
            "calibrate",
            str(project.root),
            "--include-unreviewed",
            "--points",
            "landmarks",
            "--focal-px",
            FOCAL,
            "--name",
            "unrev",
            "--log-level",
            "error",
        ]
    )
    cal = Calibration.load(project.root / "calibrations" / "unrev.toml")
    assert cal.provenance["reviewed_only"] is False


