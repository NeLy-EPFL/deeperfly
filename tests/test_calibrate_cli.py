"""``deeperfly calibrate`` end to end: label an uncalibrated project, recover its rig.

The one test worth having here is :func:`test_the_whole_from_scratch_flow`, which walks the
path a new user actually takes -- videos, a project, hand labels, a solve -- and then checks
the recovered rig against the rig the labels were *generated* from. Everything else guards a
refusal: this command's job is as much to decline an under-determined solve as to perform a
good one.
"""

from __future__ import annotations

import numpy as np
import pytest
from helpers import CAMERA_NAMES

from deeperfly import cli
from deeperfly.calibration import Calibration
from deeperfly.config import Config
from deeperfly.gui.labels import (
    Labels,
    LandmarkLabels,
    labels_identity,
    save_labels,
)
from deeperfly.landmarks import Landmark, LandmarkSet
from deeperfly.project import Project

HEIGHT, WIDTH = 512, 960
SIZES = {name: (HEIGHT, WIDTH) for name in CAMERA_NAMES}
FOCAL = "22388.125"


@pytest.fixture
def truth():
    return Config.default().camera_group(image_sizes=SIZES)


def _labelled_project(
    tmp_path,
    truth,
    *,
    n_static=6,
    n_frames=6,
    n_kp=38,
    step=3,
    reviewed=True,
    noise=0.4,
):
    """A project whose one recording carries labels generated by ``truth``.

    No video files: the labels' *identity* is written directly, which is all `calibrate`
    reads. That keeps the test about the solve rather than about video decoding (which
    ``test_gui_uncalibrated`` already covers).
    """
    project = Project.create(tmp_path / "proj", name="scratch", skeleton="fly38")
    LandmarkSet([Landmark(name=f"lm{i}", static=True) for i in range(n_static)]).save(
        project.root
    )

    rec = tmp_path / "flyA"
    rec.mkdir()
    for name in CAMERA_NAMES:
        (rec / f"{name}.mp4").write_bytes(b"\0" * (1000 + len(name)))
    entry = project.add_recording(rec)

    rng = np.random.default_rng(0)
    n_views = len(CAMERA_NAMES)
    static3d = rng.uniform(-25, 25, size=(n_static, 3))
    animal3d = rng.uniform(-4, 4, size=(n_frames, 38, 3))

    labels = Labels.empty(n_views, n_frames, 38)
    landmarks = LandmarkLabels.empty(
        n_views, n_frames, [f"lm{i}" for i in range(n_static)]
    )
    for t in range(n_frames):
        lm_px = np.asarray(truth.project(static3d)) + rng.normal(
            0, noise, (n_views, n_static, 2)
        )
        kp_px = np.asarray(truth.project(animal3d[t])) + rng.normal(
            0, noise, (n_views, 38, 2)
        )
        for v in range(n_views):
            for i in range(n_static):
                landmarks.set(v, t, i, lm_px[v, i])
            for p in range(0, n_kp, step):
                labels.set_gt(v, t, p, kp_px[v, p])
        if reviewed:
            labels.set_reviewed(t, True)

    identity = labels_identity(
        point_names=list(project.skeleton().point_names),
        camera_names=list(CAMERA_NAMES),
        n_frames=n_frames,
        image_sizes=SIZES,
    )
    save_labels(
        project.labels_path(entry), labels, identity=identity, landmarks=landmarks
    )
    return project, entry


def _centre_error_pct(truth, solved) -> float:
    a = np.stack([truth[n].position for n in CAMERA_NAMES])
    b = np.stack([solved[n].position for n in CAMERA_NAMES])
    ac, bc = a - a.mean(0), b - b.mean(0)
    u, s, vt = np.linalg.svd(bc.T @ ac)
    rot = u @ vt
    if np.linalg.det(rot) < 0:
        u[:, -1] *= -1
        rot = u @ vt
    scale = s.sum() / (bc**2).sum()
    err = np.linalg.norm(scale * (bc @ rot) - ac, axis=1)
    return float(100 * err.max() / np.linalg.norm(ac, axis=1).mean())


# -- the whole flow ------------------------------------------------------------


def test_the_whole_from_scratch_flow(tmp_path, truth, capsys):
    """Uncalibrated project + hand labels -> the rig they were generated from."""
    project, _ = _labelled_project(tmp_path, truth)
    assert project.calibration is None  # uncalibrated to begin with

    cli.main(
        [
            "calibrate",
            str(project.root),
            "--points",
            "both",
            "--focal-px",
            FOCAL,
            "--name",
            "from-labels",
            "--accept",
            "--log-level",
            "error",
        ]
    )
    out = capsys.readouterr().out
    assert "accepted" in out

    reloaded = Project.load(project.root)
    assert reloaded.calibration == "calibrations/from-labels.toml"

    cal = Calibration.load(project.root / "calibrations" / "from-labels.toml")
    assert cal.provenance["method"] == "labels_ba"
    assert cal.provenance["intrinsics"] == "given"
    assert cal.provenance["reviewed_only"] is True
    assert cal.units == "arbitrary"  # nothing pinned the scale
    assert cal.quality["rms_reproj_px"] < 2.0
    assert _centre_error_pct(truth, cal.cameras) < 1.0
    # The machine-readable report lands beside it.
    assert (project.root / "calibrations" / "from-labels.report.json").exists()


@pytest.mark.parametrize("points", ["landmarks", "keypoints", "both"])
def test_each_point_source_can_drive_the_solve(tmp_path, truth, points):
    """The operator's choice, per the ask: skeleton points, landmarks, or both."""
    project, _ = _labelled_project(tmp_path, truth)
    cli.main(
        [
            "calibrate",
            str(project.root),
            "--points",
            points,
            "--focal-px",
            FOCAL,
            "--name",
            points,
            "--log-level",
            "error",
        ]
    )
    cal = Calibration.load(project.root / "calibrations" / f"{points}.toml")
    assert cal.provenance["points"] == points
    assert _centre_error_pct(truth, cal.cameras) < 2.0


def test_nothing_is_accepted_without_the_flag(tmp_path, truth):
    """A bad solve must not be able to silently replace a good rig."""
    project, _ = _labelled_project(tmp_path, truth)
    cli.main(
        ["calibrate", str(project.root), "--focal-px", FOCAL, "--log-level", "error"]
    )
    assert (project.root / "calibrations" / "from-labels.toml").exists()
    assert Project.load(project.root).calibration is None


def test_dry_run_reports_readiness_and_writes_nothing(tmp_path, truth, capsys):
    project, _ = _labelled_project(tmp_path, truth)
